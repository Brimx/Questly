CREATE TABLE usuario_persona (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo varchar(150) NOT NULL UNIQUE,
    nombre varchar(100) NOT NULL,
    rol varchar(20) NOT NULL DEFAULT 'aprendiz'
        CHECK (rol IN ('aprendiz', 'maestro', 'experto')),
    fecha_nacimiento date,
    descripcion_tu text,
    puntos_experiencia integer NOT NULL DEFAULT 0
        CHECK (puntos_experiencia >= 0),
    nivel integer NOT NULL DEFAULT 1
        CHECK (nivel >= 1)
);

CREATE TABLE habito_tarea (
    id_habito integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(150) NOT NULL,
    nivel_importancia varchar(20) NOT NULL DEFAULT 'media'
        CHECK (nivel_importancia IN ('alta', 'media', 'baja')),
    tiempo_invertido integer
        CHECK (tiempo_invertido IS NULL OR tiempo_invertido > 0),
    fecha_inicio date NOT NULL DEFAULT CURRENT_DATE,
    fecha_final date
        CHECK (fecha_final IS NULL OR fecha_final >= fecha_inicio),
    frecuencia varchar(30) NOT NULL DEFAULT 'diaria'
        CHECK (frecuencia IN ('diaria', 'semanal', 'mensual')),
    usuario_id integer NOT NULL
        REFERENCES usuario_persona (id_usuario) ON DELETE CASCADE
);
CREATE INDEX idx_habito_tarea_usuario ON habito_tarea (usuario_id);

CREATE TABLE meta (
    id_meta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion varchar(255) NOT NULL,
    valor_objetivo integer NOT NULL CHECK (valor_objetivo > 0),
    fecha_limite date,
    habito_id integer
        REFERENCES habito_tarea (id_habito) ON DELETE SET NULL
);
CREATE INDEX idx_meta_habito ON meta (habito_id);

CREATE TABLE recompensa (
    id_recompensa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL UNIQUE,
    descripcion text,
    puntos_necesarios integer NOT NULL CHECK (puntos_necesarios > 0),
    habito_id integer
        REFERENCES habito_tarea (id_habito) ON DELETE SET NULL
);
CREATE INDEX idx_recompensa_habito ON recompensa (habito_id);

CREATE TABLE usuario_recompensa (
    usuario_id integer NOT NULL
        REFERENCES usuario_persona (id_usuario) ON DELETE CASCADE,
    recompensa_id integer NOT NULL
        REFERENCES recompensa (id_recompensa) ON DELETE RESTRICT,
    fecha_obtencion date NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (usuario_id, recompensa_id)
);
CREATE INDEX idx_usuario_recompensa_recompensa ON usuario_recompensa (recompensa_id);

CREATE TABLE recordatorio (
    id_recordatorio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora timestamp NOT NULL,
    mensaje varchar(255) NOT NULL,
    repeticion varchar(30) NOT NULL DEFAULT 'única'
        CHECK (repeticion IN ('única', 'diaria', 'semanal', 'mensual')),
    habito_id integer NOT NULL
        REFERENCES habito_tarea (id_habito) ON DELETE CASCADE
);
CREATE INDEX idx_recordatorio_habito ON recordatorio (habito_id);

CREATE TABLE habilidad (
    id_habilidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_habilidad varchar(100) NOT NULL,
    descripcion text,
    nivel_habilidad integer NOT NULL DEFAULT 1
        CHECK (nivel_habilidad BETWEEN 1 AND 10),
    tipo_origen varchar(10) NOT NULL
        CHECK (tipo_origen IN ('sistema', 'usuario')),
    usuario_id integer NOT NULL
        REFERENCES usuario_persona (id_usuario) ON DELETE CASCADE,
    CONSTRAINT uq_habilidad_usuario UNIQUE (nombre_habilidad, usuario_id)
);

CREATE TABLE animo (
    id_animo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_actual varchar(30) NOT NULL
        CHECK (estado_actual IN ('excelente', 'bien', 'normal', 'triste', 'estresado')),
    comentario text,
    fecha_registro timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id integer NOT NULL
        REFERENCES usuario_persona (id_usuario) ON DELETE CASCADE
);
CREATE INDEX idx_animo_usuario_fecha ON animo (usuario_id, fecha_registro);

CREATE TABLE cumplimiento (
    id_cumplimiento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_cumplimiento date NOT NULL,
    habito_id integer NOT NULL
        REFERENCES habito_tarea (id_habito) ON DELETE CASCADE,
    CONSTRAINT uq_cumplimiento_habito_fecha UNIQUE (habito_id, fecha_cumplimiento)
);
CREATE INDEX idx_cumplimiento_fecha ON cumplimiento (fecha_cumplimiento);

-- Una fila por hábito. Las semanas comienzan el lunes y los meses el día 1.
-- El porcentaje usa los períodos desde el inicio hasta hoy (o fecha_final).
-- La racha cuenta períodos consecutivos completados hasta el último período esperado.
CREATE VIEW estadistica_habito AS
WITH configuracion AS (
    SELECT
        h.id_habito,
        h.usuario_id,
        h.frecuencia,
        date_trunc(
            CASE h.frecuencia
                WHEN 'diaria' THEN 'day'
                WHEN 'semanal' THEN 'week'
                ELSE 'month'
            END,
            h.fecha_inicio::timestamp
        )::date AS periodo_inicio,
        date_trunc(
            CASE h.frecuencia
                WHEN 'diaria' THEN 'day'
                WHEN 'semanal' THEN 'week'
                ELSE 'month'
            END,
            LEAST(CURRENT_DATE, COALESCE(h.fecha_final, CURRENT_DATE))::timestamp
        )::date AS periodo_fin
    FROM habito_tarea AS h
),
periodos AS (
    SELECT
        c.id_habito,
        serie.periodo::date AS periodo,
        c.frecuencia
    FROM configuracion AS c
    CROSS JOIN LATERAL generate_series(
        c.periodo_inicio::timestamp,
        c.periodo_fin::timestamp,
        CASE c.frecuencia
            WHEN 'diaria' THEN INTERVAL '1 day'
            WHEN 'semanal' THEN INTERVAL '1 week'
            ELSE INTERVAL '1 month'
        END
    ) AS serie(periodo)
),
periodos_cumplidos AS (
    SELECT
        p.id_habito,
        p.periodo,
        COUNT(c.id_cumplimiento) > 0 AS completado
    FROM periodos AS p
    LEFT JOIN cumplimiento AS c
        ON c.habito_id = p.id_habito
        AND date_trunc(
            CASE p.frecuencia
                WHEN 'diaria' THEN 'day'
                WHEN 'semanal' THEN 'week'
                ELSE 'month'
            END,
            c.fecha_cumplimiento::timestamp
        )::date = p.periodo
    GROUP BY p.id_habito, p.periodo
),
periodos_ordenados AS (
    SELECT
        pc.id_habito,
        pc.periodo,
        pc.completado,
        ROW_NUMBER() OVER (
            PARTITION BY pc.id_habito ORDER BY pc.periodo DESC
        ) AS posicion
    FROM periodos_cumplidos AS pc
),
primer_faltante AS (
    SELECT
        po.id_habito,
        MIN(po.posicion) FILTER (WHERE NOT po.completado) AS posicion_faltante
    FROM periodos_ordenados AS po
    GROUP BY po.id_habito
)
SELECT
    h.id_habito,
    h.usuario_id,
    COUNT(po.periodo) FILTER (WHERE po.completado) AS total_completado,
    ROUND(
        100.0 * COUNT(po.periodo) FILTER (WHERE po.completado)
        / NULLIF(COUNT(po.periodo), 0),
        2
    ) AS porcentaje_cumplido,
    COUNT(po.periodo) FILTER (
        WHERE po.completado
          AND (pf.posicion_faltante IS NULL OR po.posicion < pf.posicion_faltante)
    ) AS racha_actual
FROM habito_tarea AS h
LEFT JOIN periodos_ordenados AS po ON po.id_habito = h.id_habito
LEFT JOIN primer_faltante AS pf ON pf.id_habito = h.id_habito
GROUP BY h.id_habito, h.usuario_id, pf.posicion_faltante;

CREATE INDEX idx_habilidad_usuario ON habilidad (usuario_id);
